
-- =========================================
-- TABELA: CLIENTES
-- =========================================

CREATE TABLE IF NOT EXISTS clientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cpf VARCHAR(11) NOT NULL UNIQUE,
    telefone VARCHAR(20),
    nome VARCHAR(150) NOT NULL,
    email VARCHAR(150) UNIQUE,
    senha_hash VARCHAR(100)
);

-- Garante a coluna de senha em bancos criados antes do login existir
ALTER TABLE clientes ADD COLUMN IF NOT EXISTS senha_hash VARCHAR(100);

-- =========================================
-- TABELA: USUARIOS DO ERP (equipe da Amaral)
-- =========================================
-- Separada de "clientes": quem compra pelo site nao entra no painel de gestao.

CREATE TABLE IF NOT EXISTS usuarios_erp (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    senha_hash VARCHAR(100) NOT NULL,
    ativo BOOLEAN DEFAULT TRUE NOT NULL,
    -- ADMIN: todas as telas | FUNCIONARIO: so Producao e Entregas
    perfil VARCHAR(20) DEFAULT 'ADMIN' NOT NULL
);

-- Garante a coluna em bancos criados antes dos perfis existirem
ALTER TABLE usuarios_erp ADD COLUMN IF NOT EXISTS perfil VARCHAR(20) DEFAULT 'ADMIN' NOT NULL;

-- =========================================
-- TABELA: PRODUTOS E VALORES (Tela 5 do ERP)
-- =========================================
-- Os precos editados no ERP sao os mesmos que o configurador do site usa.
-- "chave" liga o produto a uma opcao do configurador (FIO_12, MALHA_3, PVC...).

CREATE TABLE IF NOT EXISTS produtos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chave VARCHAR(30) UNIQUE,
    categoria VARCHAR(20) NOT NULL,
    nome VARCHAR(120) NOT NULL,
    descricao VARCHAR(255),
    unidade VARCHAR(20) NOT NULL,
    valor DECIMAL(10,2) NOT NULL,
    ativo BOOLEAN DEFAULT TRUE NOT NULL,

    CONSTRAINT chk_produto_categoria
        CHECK (categoria IN ('ARAME', 'MALHA', 'TRATAMENTO', 'ACESSORIOS')),

    CONSTRAINT chk_produto_unidade
        CHECK (unidade IN ('M2', 'METRO_LINEAR', 'UNIDADE')),

    CONSTRAINT chk_produto_valor
        CHECK (valor >= 0)
);

-- Regras do orcamento: uma linha so (id = 1)
CREATE TABLE IF NOT EXISTS regras_orcamento (
    id INT PRIMARY KEY,
    desconto_avista_pct DECIMAL(5,2) NOT NULL,
    parcelas_max INT NOT NULL
);

