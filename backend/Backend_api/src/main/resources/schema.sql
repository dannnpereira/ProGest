
-- =========================================
-- TABELA: CLIENTES
-- =========================================

CREATE TABLE IF NOT EXISTS clientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cpf VARCHAR(11) NOT NULL UNIQUE,
    telefone VARCHAR(20),
    nome VARCHAR(150) NOT NULL,
    email VARCHAR(150)
);

-- =========================================
-- TABELA: ENDERECOS
-- =========================================

CREATE TABLE IF NOT EXISTS enderecos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT NOT NULL,
    cep VARCHAR(9) NOT NULL,
    numero VARCHAR(20) NOT NULL,

    CONSTRAINT fk_endereco_cliente
        FOREIGN KEY (cliente_id)
        REFERENCES clientes(id)
        ON DELETE CASCADE
);

-- =========================================
-- TABELA: PEDIDOS
-- =========================================


CREATE TABLE IF NOT EXISTS pedidos (
    op BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fio DECIMAL(10,2),
    malha DECIMAL(10,2),
    dataentrega DATE
);
-- =========================================
-- TABELA: WORKFLOW
-- =========================================
-- Situação atual de cada pedido
CREATE TABLE IF NOT EXISTS workflow_pedidos (
    op BIGINT PRIMARY KEY,
    status VARCHAR(20) NOT NULL,
    data_atualizacao TIMESTAMP NOT NULL,

    CONSTRAINT fk_workflow_pedido
        FOREIGN KEY (op)
        REFERENCES pedidos(op),

    CONSTRAINT chk_status_workflow
        CHECK (status IN ('A_FAZER', 'EM_PROCESSO', 'ENTREGUE'))
);

-- Histórico de movimentações da produção
CREATE TABLE IF NOT EXISTS historico_workflow (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    op BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL,
    data_alteracao TIMESTAMP NOT NULL,

    CONSTRAINT fk_historico_pedido
        FOREIGN KEY (op)
        REFERENCES pedidos(op)
);
