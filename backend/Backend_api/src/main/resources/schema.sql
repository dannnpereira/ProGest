-- =========================================
-- FINANCEIRO DO ERP: LANCAMENTOS
-- =========================================
-- COMPRA: compra de material (descricao = material, favorecido = fornecedor)
-- DESPESA: saidas como salarios, aluguel, energia, impostos (com categoria)
-- ENTRADA: recebimentos que nao vem de pedidos do site (vendas diretas)
CREATE TABLE IF NOT EXISTS lancamentos_financeiros (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo VARCHAR(10) NOT NULL,
    data_lancamento DATE NOT NULL,
    categoria VARCHAR(20),
    descricao VARCHAR(255) NOT NULL,
    favorecido VARCHAR(150),
    quantidade VARCHAR(100),
    valor DECIMAL(12,2) NOT NULL,
    status VARCHAR(10) NOT NULL,

    CONSTRAINT chk_lancamento_tipo
        CHECK (tipo IN ('COMPRA', 'DESPESA', 'ENTRADA')),

    CONSTRAINT chk_lancamento_status
        CHECK (status IN ('PAGO', 'A_PAGAR', 'ATRASADO')),

    CONSTRAINT chk_lancamento_categoria
        CHECK (categoria IS NULL OR categoria IN
            ('SALARIOS', 'ENCARGOS', 'ALUGUEL', 'ENERGIA', 'AGUA', 'IMPOSTOS', 'VEICULOS', 'FRETE', 'OUTROS')),

    CONSTRAINT chk_lancamento_valor
        CHECK (valor > 0)
);
