-- =========================================
-- TABELA DE PRECOS (Produtos e Valores do ERP)
-- =========================================
-- Preco por combinacao: arame + malha + tratamento. Tela (M2) vira opcao no site;
-- arame avulso (KG) nao tem malha e so aparece no ERP.

CREATE TABLE IF NOT EXISTS precos_tela (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    arame VARCHAR(30) NOT NULL,
    malha VARCHAR(30),
    tratamento VARCHAR(30) NOT NULL,
    unidade VARCHAR(10) NOT NULL,
    peso_kg_m2 DECIMAL(8,3),
    valor_vista DECIMAL(10,2) NOT NULL,
    valor_prazo DECIMAL(10,2),
    excluido BOOLEAN DEFAULT FALSE NOT NULL,

    CONSTRAINT chk_preco_unidade CHECK (unidade IN ('M2', 'KG')),
    CONSTRAINT chk_preco_valores CHECK (valor_vista >= 0 AND (valor_prazo IS NULL OR valor_prazo >= 0))
);

-- Mudancas de dados que rodam uma vez so (o schema.sql roda a cada inicio)
