-- =========================================
-- TABELA: PEDIDOS FEITOS PELO SITE
-- =========================================
-- Criados no configurador pelo cliente logado; aprovados/recusados e
-- acompanhados na produção pelo ERP. Valores calculados pelo backend.

CREATE TABLE IF NOT EXISTS pedidos_cliente (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(20) UNIQUE,
    cliente_id BIGINT NOT NULL,
    criado_em TIMESTAMP WITH TIME ZONE NOT NULL,
    status VARCHAR(25) NOT NULL,

    arame VARCHAR(30) NOT NULL,
    malha VARCHAR(30) NOT NULL,
    tratamento VARCHAR(30) NOT NULL,
    altura_m DECIMAL(6,2) NOT NULL,
    comprimento_m DECIMAL(8,2) NOT NULL,

    entrega BOOLEAN NOT NULL,
    cep VARCHAR(9),
    endereco VARCHAR(255),
    cidade VARCHAR(100),
    uf VARCHAR(2),
    distancia_km INT,

    valor_materia_prima DECIMAL(12,2) NOT NULL,
    valor_acessorios DECIMAL(12,2) NOT NULL,
    valor_frete DECIMAL(12,2) NOT NULL,
    valor_desconto DECIMAL(12,2) NOT NULL,
    valor_total DECIMAL(12,2) NOT NULL,
    parcelas INT NOT NULL,
    valor_parcela DECIMAL(12,2) NOT NULL,

    aprovado_em TIMESTAMP WITH TIME ZONE,
    recusado_em TIMESTAMP WITH TIME ZONE,
    motivo_recusa VARCHAR(500),
    producao_iniciada_em TIMESTAMP WITH TIME ZONE,
    entregue_em TIMESTAMP WITH TIME ZONE,
    previsao_entrega DATE,

    CONSTRAINT fk_pedido_cliente_cliente
        FOREIGN KEY (cliente_id) REFERENCES clientes(id),

    CONSTRAINT chk_pedido_cliente_status
        CHECK (status IN ('AGUARDANDO_APROVACAO', 'RECUSADO', 'A_FAZER', 'EM_PROCESSO', 'ENTREGUE'))
);

-- Nome dos produtos no momento do pedido: o pedido continua certo mesmo que
-- o produto seja renomeado ou excluido depois no ERP.
ALTER TABLE pedidos_cliente ADD COLUMN IF NOT EXISTS arame_nome VARCHAR(120);
ALTER TABLE pedidos_cliente ADD COLUMN IF NOT EXISTS malha_nome VARCHAR(120);
ALTER TABLE pedidos_cliente ADD COLUMN IF NOT EXISTS tratamento_nome VARCHAR(120);

UPDATE pedidos_cliente SET arame_nome = (SELECT p.nome FROM produtos p WHERE p.chave = pedidos_cliente.arame)
WHERE arame_nome IS NULL;
UPDATE pedidos_cliente SET malha_nome = (SELECT p.nome FROM produtos p WHERE p.chave = pedidos_cliente.malha)
WHERE malha_nome IS NULL;
UPDATE pedidos_cliente SET tratamento_nome = (SELECT p.nome FROM produtos p WHERE p.chave = pedidos_cliente.tratamento)
WHERE tratamento_nome IS NULL;

-- =========================================
-- TABELA: ENDERECOS
-- =========================================

CREATE TABLE IF NOT EXISTS enderecos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT NOT NULL,
    cep VARCHAR(9) NOT NULL,
    numero VARCHAR(20) NOT NULL,

    CONSTRAINT fk_endereco_cliente
        FOREIGN KEY (cliente_id)
        REFERENCES clientes(id)
        ON DELETE CASCADE
);

-- =========================================
-- TABELA: PEDIDOS
-- =========================================


CREATE TABLE IF NOT EXISTS pedidos (
    op BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fio DECIMAL(10,2),
    malha DECIMAL(10,2),
    dataentrega DATE,
    preco DECIMAL(10,2)
);
-- =========================================
-- TABELA: WORKFLOW
-- =========================================
-- Situação atual de cada pedido
CREATE TABLE IF NOT EXISTS workflow_pedidos (
    op BIGINT PRIMARY KEY,
    status VARCHAR(20) NOT NULL,
    data_atualizacao TIMESTAMP NOT NULL,

    CONSTRAINT fk_workflow_pedido
        FOREIGN KEY (op)
        REFERENCES pedidos(op),

    CONSTRAINT chk_status_workflow
        CHECK (status IN ('A_FAZER', 'EM_PROCESSO', 'ENTREGUE'))
);

-- Histórico de movimentações da produção
CREATE TABLE IF NOT EXISTS historico_workflow (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    op BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL,
    data_alteracao TIMESTAMP NOT NULL,

    CONSTRAINT fk_historico_pedido
        FOREIGN KEY (op)
        REFERENCES pedidos(op)
);
-- =========================================
-- TABELA: FINANCEIRO
-- =========================================
CREATE TABLE IF NOT EXISTS transacoes_financeiras (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    op BIGINT,
    tipo VARCHAR(10) NOT NULL,
    tipo_despesa VARCHAR(20),
    descricao VARCHAR(255) NOT NULL,
    fornecedores VARCHAR(255),
    valor DECIMAL(10,2) NOT NULL,
    data_movimentacao DATE NOT NULL,

    CONSTRAINT fk_transacao_pedido
        FOREIGN KEY (op) REFERENCES pedidos(op),

    CONSTRAINT chk_tipo_transacao
        CHECK (tipo IN ('ENTRADA', 'SAIDA')),

    CONSTRAINT chk_valor_transacao
        CHECK (valor > 0),

    CONSTRAINT chk_tipo_despesa
        CHECK (tipo_despesa IS NULL OR tipo_despesa IN ('IMPOSTOS', 'SALARIOS', 'INSUMOS', 'CONTAS_FIXAS'))
);
